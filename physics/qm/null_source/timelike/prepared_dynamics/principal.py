def algebra():
    h,y,z,w,C=sp.symbols('h y z w C',real=True)
    q=-1-y-h*h
    deriv=lambda f:sp.diff(f,h)*y+sp.diff(f,y)*z+sp.diff(f,z)*w+sp.diff(f,C)*30*h
    U=y*y-2*h*z+3*h**4+2*h*h-1
    V=-2*w+(12*h*h+4)*y
    Z=4*h*z+8*h*h*y-3*h**4+3*y*y+4*y-2*h*h+1
    Nt=C*V+4*y*(h*h+1)-30*Z
    J=2*C*deriv(q)+(60-4*C)*h*q-56*h-sp.Rational(56,3)*h**3
    assert sp.expand(Nt-deriv(J)+30*(y*y+(h*h+1)**2))==0
    k,x,b,r=sp.symbols('k x b r',real=True)
    xprime=2*r;xsecond=2*b-2*(k*k+q)*x
    mode_trace=-xsecond+2*h*xprime+2*y*x
    bare_trace=2*(k*k-1)*x-2*(b-2*h*r+h*h*x)
    assert sp.expand(mode_trace-bare_trace)==0
    xd=sp.Rational(1,2)/k-q/(4*k**3)
    trace_sub=-deriv(deriv(xd))+2*h*deriv(xd)+2*y*xd
    assert sp.simplify(trace_sub-y/k-V/(8*k**3))==0
    radius=sp.symbols('r',positive=True)
    f=sp.Function('f')(radius);chi=sp.sin(radius)/radius
    lhs=sp.diff(chi*f,radius,2)+2*sp.diff(chi*f,radius)/radius
    rhs=chi*(sp.diff(f,radius,2)+2*sp.cot(radius)*sp.diff(f,radius)-f)
    assert sp.trigsimp(sp.simplify(lhs-rhs))==0
    a,a1,a2,M,rho,pressure=sp.symbols('a a1 a2 M rho pressure',real=True,nonzero=True)
    constraint=a1*a1+a*a-M/(3*a*a)-sp.Rational(2,3)*a**4*rho
    dconstraint=sp.diff(constraint,a)*a1+sp.diff(constraint,a1)*a2+sp.diff(constraint,rho)*(-3*a1*(rho+pressure)/a)
    acceleration=a2+a+M/(3*a**3)-a**3*(rho-3*pressure)/3
    assert sp.factor(dconstraint-2*a1*acceleration)==0
    return {'AE_trace_is_total_derivative_plus_regular_terms':True,
      'exact_mode_trace_and_subtraction_identity':True,
      'S3_to_flat_radial_conjugation':True,'off_shell_constraint_identity':True,
      'J':str(J),'integrated_trace':'Pprime-2*h*P-J/(480*pi^2)=Kinit+integral(6*a^2*q-2*M2/a^2-((hprime)^2+(h^2+1)^2)/(16*pi^2))'}

def compute():
    a0=iv.sqrt(3)*32768
    C=19+15*(iv.log(a0*a0/4)+2*iv.euler)
    alpha=a0*iv.exp(I(Q(19,30)))
    assert bg.lower(alpha)>106921 and bg.upper(alpha)<106922
    cutoff={}
    for N in [256,512,1024,65536]:
        harmonic=I(sum((Q(1,k) for k in range(1,N+1)),Q(0)))
        cutoff[str(N)]=old.pair(C-30*harmonic)
    assert bg.lower(old.read_pair(cutoff['1024']))>0
    assert bg.upper(old.read_pair(cutoff['65536']))<0
    windows=[]
    for power,base_gate,theta_gate,full_gate in [(20,95,Q(2,10**12),96),(21,74,Q(1,10**12),75)]:
        T=I(Q(1,2**power))
        logarg=iv.log(1/(alpha*T))
        assert bg.lower(logarg)>0
        M=8*iv.pi**2*iv.e/logarg
        compact=T*T/6/(1-T*T/6)
        variable=I(3)*T*T/2
        original_family_hprime=2/(1-2*T*T)**2+I(Q(1,256))
        assert bg.upper(original_family_hprime)<3
        theta=M*(compact+variable)/(8*iv.pi**2)
        full=M/(1-theta)
        assert bg.upper(M)<base_gate and bg.upper(theta)<bg.lower(I(theta_gate)) and bg.upper(full)<full_gate
        einstein_budget=3*a0*a0*iv.exp(2*variable)*T*T*full
        windows.append({'T':str(Q(1,2**power)),'alpha_T':old.pair(alpha*T),
           'flat_contact_inverse_bound':old.pair(pb.initial.top(M)),
           'compact_perturbation_bound':old.pair(compact),
           'variable_contact_bound_divided_by_c':old.pair(variable),
           'proper_clock_duration_enclosure':old.pair(a0*T*bg.box(bg.lower(iv.exp(-variable)),bg.upper(iv.exp(variable)))),
           'original_family_hprime_bound':old.pair(original_family_hprime),
           'neumann_ratio_bound':old.pair(pb.initial.top(theta)),
           'inverse_bound':old.pair(pb.initial.top(full)),
           'outward_inverse_gate':full_gate,
           'fixed_a_Einstein_term_only_contraction_budget':old.pair(pb.initial.top(einstein_budget)),
           'full_nonlinear_contraction_proved':False})
    return {'schema':'ueot-prepared-principal-inverse/1','status':'PASS','algebra':algebra(),
      'lambda':32768,'AE_mu':1,'AE_alpha':0,'extra_finite_terms':0,
      'initial_C':old.pair(C),'frozen_principal_laplace_pole':old.pair(alpha),
      'pole_exact':'sqrt(3)*32768*exp(19/30)',
      'finite_cutoff_contact_coefficient_C_minus_30H_N':cutoff,
      'windows':windows,
      'geometry_ball':'a(0)=sqrt(3)*32768, h(0)=0, sup|hprime|<=3. A new physical solution must separately be shown to enter and remain in this ball.',
      'domain':'X_T=continuous f with f(0)=0; causal closed Volterra domain generated by J_alpha convolution. Smooth forcing compatibility must be established separately.',
      'operator':'Ts - C(eta)/(240*pi^2)*Id, including fixed AE contact and actual-family variable C',
      'scope':{'actual_principal_inverse':True,'regular_state_response_norm_certified':False,
               'full_SCE_existence':False,'smooth_Hadamard_release_constructed':False,
               'physical_instability_inferred_from_principal_pole':False},
      'source_identity':{Path(__file__).name:hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}}

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--write',action='store_true');ap.add_argument('--check',action='store_true')
