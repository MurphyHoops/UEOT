from pathlib import Path
import datetime
import fcntl
import hashlib
import json
import os
import signal
import subprocess
import sys
import time

base = Path('/workspace/scratch/9a8d58b21e30')
root = base / 'tmp/finite-encoding-20261021/resume-killed-qsd-binding'
source = root / 'SameSourceQSDBinding.lean'
number = int(sys.argv[1])
timeout = 180

lock = (root / 'compile.lock').open('a')
fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)

native_status = base / 'tmp/registered-interfaces-20261021/native-repair-sequence-2/STATUS.json'
native = json.loads(native_status.read_text())
if not (native.get('state') == 'PASS_NATIVE_AND_PROVISIONAL_EVIDENCE'
        and all(x.get('exit_code') == 0 for x in native.get('results', []))
        and {x.get('label') for x in native.get('results', [])}
        >= {'native_pipeline', 'observed_finalizer'}):
    print(json.dumps({'status': 'PAUSED_NATIVE_NOT_COMPLETE', 'observed': native}), flush=True)
    raise SystemExit(75)

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

bridge_root = base / 'tmp/finite-encoding-20261021/resume-source-bridge'
bridge_cache = bridge_root / 'lean-attempt-002'
killed_root = base / 'tmp/finite-encoding-20261021/resume-killed-formalization'
killed_cache = killed_root / 'lean-attempt-010'
k2_root = base / 'tmp/finite-encoding-20261021/general-k2'
k2_cache = k2_root / 'lean-attempt-004'
pins = {
    k2_root / 'SameSourceConditionedTerminal.lean':
        '8114278dc02e54f681bd576cf62af0dcc83df47a5b4a61bdc506a868750aea3c',
    k2_cache / 'SameSourceConditionedTerminal.olean':
        '3882f4be785ccafeb9352042e2c95bc2978570ea0e15d7def2a12e3eaf06fbeb',
    bridge_root / 'SourcePolicyPathBridge.lean':
        '108500fc13229b8faffc9829d886313167142075112bc3f6c023a086c074ae91',
    bridge_cache / 'SourcePolicyPathBridge.olean':
        '0ef1132fbfb24b0e571693de99e2729f9a8ede4aa41203fb4b3be67d46915748',
    killed_root / 'SameSourceKilledPath.lean':
        'fa4f5ce017d6bfa4d9f3fe77805ad629f1c04f34a7ac3495c9114c432bc6c826',
    killed_cache / 'SameSourceKilledPath.olean':
        '91c3d26034d72d7abeb140d057c78b55296d4e4e7450cf5b291ccc3ad748d1e5',
}
for path, expected in pins.items():
    assert sha(path) == expected, f'Dependency identity changed: {path}'

attempt = root / f'lean-attempt-{number:03d}'
attempt.mkdir(exist_ok=False)
snapshot = attempt / source.name
snapshot.write_bytes(source.read_bytes())
original = root / 'SameSourceQSDBinding_v1.lean'
if not original.exists():
    original.write_bytes(source.read_bytes())

runtime = base / 'tmp/registered-interfaces-20261021/linux-runtime/lean-4.33.1-linux/bin'
cwd = base / 'ueot-integration/formalization/ueot-core'
private_path = os.pathsep.join([str(k2_cache), str(killed_cache), str(bridge_cache)])
after_lake = ('import os,sys; '
              'os.environ["LEAN_PATH"]=sys.argv[1]+os.pathsep+os.environ.get("LEAN_PATH",""); '
              'os.execv(sys.argv[2],sys.argv[2:])')
cmd = [str(runtime / 'lake'), 'env', sys.executable, '-c', after_lake,
       private_path, str(runtime / 'lean'), '--root=' + str(root),
       '-o', str(attempt / 'SameSourceQSDBinding.olean'), str(source)]
env = os.environ.copy()
env['LEAN_NUM_THREADS'] = '1'
env['PATH'] = str(runtime) + os.pathsep + env.get('PATH', '')
receipt = {
    'schema': 'UEOT_PRIVATE_QSD_SOURCE_BINDING_COMPILE_ATTEMPT_V1',
    'attempt': number,
    'status': 'RUNNING',
    'source': str(source),
    'source_sha256': sha(source),
    'source_snapshot': str(snapshot),
    'command': cmd,
    'cwd': str(cwd),
    'LEAN_NUM_THREADS': '1',
    'timeout_seconds': timeout,
    'started_utc': datetime.datetime.now(datetime.timezone.utc).isoformat(),
    'root_authorization': 'Focused private QSD source-binding compilation authorized by root after actual native sequence 2 and finalizer completed; reuse passed general K2; no production, books, Git, or native changes.',
    'native_gate': {'path': str(native_status), 'sha256': sha(native_status), 'state': native['state'], 'results': native['results']},
    'dependency_pins': {str(path): expected for path, expected in pins.items()},
    'lean_toolchain_sha256': sha(cwd / 'lean-toolchain'),
    'lake_manifest_sha256': sha(cwd / 'lake-manifest.json'),
    'full_build_status': {
        'path': str(base / 'tmp/registered-interfaces-20261021/linux-build-attempt-9/STATUS.json'),
        'sha256': sha(base / 'tmp/registered-interfaces-20261021/linux-build-attempt-9/STATUS.json'),
    },
    'production_source_manifest': {
        'path': str(base / 'tmp/registered-interfaces-20261021/linux-build-attempt-9/SOURCE_MANIFEST.json'),
        'sha256': sha(base / 'tmp/registered-interfaces-20261021/linux-build-attempt-9/SOURCE_MANIFEST.json'),
        'scope': 'Existing completed build input receipt, not regenerated by this private attempt.',
    },
    'production_mutated': False,
    'lake_build_run': False,
    'native_run': False,
}
status = attempt / 'STATUS.json'
status.write_text(json.dumps(receipt, indent=2) + '\n')
log = attempt / 'lean.log'
start = time.monotonic()
with log.open('wb') as output:
    process = subprocess.Popen(cmd, cwd=cwd, env=env, stdout=output,
                               stderr=subprocess.STDOUT, start_new_session=True)
    receipt['process_group'] = process.pid
    status.write_text(json.dumps(receipt, indent=2) + '\n')
    print(json.dumps({'status': 'RUNNING', 'attempt': number, 'child_pid': process.pid,
                      'source_sha256': receipt['source_sha256'], 'timeout_seconds': timeout}), flush=True)
    timed_out = False
    try:
        code = process.wait(timeout=timeout)
    except subprocess.TimeoutExpired:
        timed_out = True
        os.killpg(process.pid, signal.SIGTERM)
        try:
            code = process.wait(timeout=5)
        except subprocess.TimeoutExpired:
            os.killpg(process.pid, signal.SIGKILL)
            code = process.wait()

receipt.update(
    status='TIMEOUT' if timed_out else ('PASS' if code == 0 else 'FAIL'),
    exit_code=code,
    timed_out=timed_out,
    elapsed_seconds=round(time.monotonic() - start, 3),
    finished_utc=datetime.datetime.now(datetime.timezone.utc).isoformat(),
    stdout_stderr_log=str(log),
    log_sha256=sha(log),
    source_sha256_after=sha(source),
)
olean = attempt / 'SameSourceQSDBinding.olean'
if olean.exists():
    receipt['olean_sha256'] = sha(olean)
status.write_text(json.dumps(receipt, indent=2) + '\n')
print(json.dumps({key: receipt[key] for key in
                  ['status', 'exit_code', 'timed_out', 'elapsed_seconds']}), flush=True)
print(log.read_text(errors='replace'), flush=True)
raise SystemExit(124 if timed_out else (code if code >= 0 else 1))
